export function getDesignedFormError(message?: string | null): string | undefined {
  if (!message) return undefined;
  // 디자인에서 줄바꿈된 문구도 원래 줄바꿈을 보존해 표시합니다.
  const normalized = message.replace(/\s+/g, ' ').trim();
  return DESIGNED_FORM_ERRORS.has(normalized) ? message : undefined;
}
